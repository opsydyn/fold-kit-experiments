// JSON Schema for foldkit-viz's PlotSpec, generated from src/plot/types.ts.
//
// Run from packages/foldkit-viz. Writes schema/plot-spec.schema.json, published
// as @opsydyn/foldkit-viz/plot-spec.schema.json, so programs in other languages
// (Rust with serde, Python) can write specs and check them before plotting.
// With --check it compares against the committed file instead, and fails if the
// types changed without the schema.
//
// Two adjustments after generation, both because a schema describes JSON:
// - A Column is a JSON array of values. In JavaScript it may also be a typed
//   array, which the generator would otherwise describe as an object.
// - TypeScript's utility types leak descriptions such as "Make all properties
//   in T readonly", which say nothing about the spec.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

import type * as Generator from 'ts-json-schema-generator';

const packageDir = process.cwd();
// The generator resolves from the package being described, which pins its version.
const { createGenerator }: typeof Generator = await import(
  createRequire(join(packageDir, 'package.json')).resolve('ts-json-schema-generator')
);
const schemaFile = join(packageDir, 'schema', 'plot-spec.schema.json');

const generated = createGenerator({
  path: join(packageDir, 'src', 'plot', 'types.ts'),
  tsconfig: join(packageDir, 'tsconfig.json'),
  type: 'PlotSpec',
  expose: 'export',
  topRef: true,
  skipTypeCheck: true,
}).createSchema('PlotSpec');

const UTILITY_DESCRIPTION = /^Make all properties in T /;

const definitions = generated.definitions ?? {};
const schema = {
  $schema: generated.$schema,
  $id: 'https://unpkg.com/@opsydyn/foldkit-viz/schema/plot-spec.schema.json',
  title: 'foldkit-viz plot spec',
  $comment:
    'Generated by tools/plot-schema.ts from packages/foldkit-viz/src/plot/types.ts. Do not edit by hand.',
  $ref: generated.$ref,
  definitions: {
    ...definitions,
    Column: {
      type: 'array',
      items: { $ref: '#/definitions/Value' },
      description:
        "One field's values. In JSON, an array; in JavaScript a column may also be a typed array such as Float64Array.",
    },
  },
};

// Written without the descriptions TypeScript's utility types attach, at any depth.
const text = `${JSON.stringify(
  schema,
  (key, value) =>
    key === 'description' && UTILITY_DESCRIPTION.test(String(value)) ? undefined : value,
  2,
)}\n`;

if (process.argv.includes('--check')) {
  const committed = existsSync(schemaFile) ? readFileSync(schemaFile, 'utf8') : '';
  if (committed !== text) {
    console.error(
      'foldkit-viz: schema/plot-spec.schema.json differs from src/plot/types.ts. Run `bun run schema:write` and commit it.',
    );
    process.exit(1);
  }
  console.log(
    `foldkit-viz: plot spec schema matches the types (${Object.keys(definitions).length} definitions).`,
  );
} else {
  mkdirSync(join(packageDir, 'schema'), { recursive: true });
  writeFileSync(schemaFile, text);
  console.log(
    `foldkit-viz: wrote schema/plot-spec.schema.json (${Object.keys(definitions).length} definitions).`,
  );
}
