// Public type-surface report for a package with many subpath exports.
//
// Run from a package directory after it is built. For every `exports` entry
// with types, it lists each exported name with its declared signature, and
// writes etc/api-surface.md. With --check it compares against that file
// instead, and fails if the public surface changed without the report.
//
// API Extractor reports one entry point per run; foldkit-viz and astro-foldkit
// export dozens, so this walks them all with one TypeScript program.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';

import type * as TS from 'typescript';

const packageDir = process.cwd();
// TypeScript resolves from the package being reported, which pins its own version.
const load = createRequire(join(packageDir, 'package.json'));
const ts: typeof TS = load('typescript');

interface ExportCondition {
  readonly types?: string;
}
interface PackageManifest {
  readonly name: string;
  readonly exports?: Readonly<Record<string, ExportCondition>>;
}

const manifest: PackageManifest = JSON.parse(
  readFileSync(join(packageDir, 'package.json'), 'utf8'),
);
const entries = Object.entries(manifest.exports ?? {})
  .flatMap(([subpath, condition]) =>
    condition.types === undefined ? [] : [{ subpath, file: resolve(packageDir, condition.types) }],
  )
  .sort((a, b) => a.subpath.localeCompare(b.subpath));

const missing = entries.filter(({ file }) => !existsSync(file));
if (missing.length > 0) {
  console.error(`Build ${manifest.name} first; missing ${missing.map((m) => m.file).join(', ')}`);
  process.exit(1);
}

const program = ts.createProgram(
  entries.map(({ file }) => file),
  {
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
    skipLibCheck: true,
    noEmit: true,
    types: [],
  },
);
const checker = program.getTypeChecker();
/** Comments and runs of blank space are not part of the surface. */
const tidy = (text: string): string =>
  text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .split('\n')
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== '')
    .join('\n')
    .replace(/^declare /, '')
    .replace(/^export /, '');

/**
 * One exported name as its declaration in the built types, which name the
 * types they use rather than expanding them, so a diff reads like the source.
 */
function describe(name: string, exported: TS.Symbol): ReadonlyArray<string> {
  const symbol =
    (exported.flags & ts.SymbolFlags.Alias) !== 0 ? checker.getAliasedSymbol(exported) : exported;
  const declarations = symbol.declarations ?? [];
  if (declarations.length === 0) return [`${name} (no declaration)`];
  const renamed =
    symbol.name !== name && symbol.name !== 'default' ? [`// exported as ${name}`] : [];
  return [
    ...renamed,
    ...declarations.map((declaration) => {
      // A variable's text is its statement, so the keyword and type come with it.
      const node = ts.isVariableDeclaration(declaration) ? declaration.parent.parent : declaration;
      return tidy(node.getText());
    }),
  ];
}

const sections = entries.map(({ subpath, file }) => {
  const source = program.getSourceFile(file);
  const module = source === undefined ? undefined : checker.getSymbolAtLocation(source);
  if (source === undefined || module === undefined) return `## ${subpath}\n\n(no exports)\n`;
  const lines = checker
    .getExportsOfModule(module)
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((symbol) => describe(symbol.name, symbol));
  return `## ${subpath}\n\n\`\`\`ts\n${lines.join('\n')}\n\`\`\`\n`;
});

const report = [
  `# ${manifest.name} public API`,
  '',
  'Generated by tools/api-surface.ts from the built type declarations. Do not',
  'edit by hand: run `bun run api:report` after a deliberate change to the public',
  'surface, and review the diff.',
  '',
  ...sections,
].join('\n');

const reportFile = join(packageDir, 'etc', 'api-surface.md');
if (process.argv.includes('--check')) {
  const committed = existsSync(reportFile) ? readFileSync(reportFile, 'utf8') : '';
  if (committed !== report) {
    const before = new Set(committed.split('\n'));
    const after = new Set(report.split('\n'));
    const added = [...after].filter((line) => !before.has(line)).slice(0, 20);
    const removed = [...before].filter((line) => !after.has(line)).slice(0, 20);
    console.error(`${manifest.name}: the public API differs from etc/api-surface.md.`);
    for (const line of removed) console.error(`- ${line}`);
    for (const line of added) console.error(`+ ${line}`);
    console.error('Run `bun run api:report` if the change is deliberate, and commit the report.');
    process.exit(1);
  }
  console.log(
    `${manifest.name}: public API matches etc/api-surface.md (${entries.length} entry points).`,
  );
} else {
  mkdirSync(join(packageDir, 'etc'), { recursive: true });
  writeFileSync(reportFile, report);
  console.log(`${manifest.name}: wrote etc/api-surface.md (${entries.length} entry points).`);
}
